#include <stdio.h>

int main() {
    float a = 4.0;
    float b = 8.0;
    float c = 3.0;
    float hasil = (a * b) / c;

    printf("Variabel a bernilai %.0f\n", a);
    printf("Variabel b bernilai %.0f\n", b);
    printf("Variabel c bernilai %.0f\n", c);
    printf("Hasil dari a dikali b dibagi c adalah %f\n", hasil);

    return 0;
}